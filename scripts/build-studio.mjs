#!/usr/bin/env node
/**
 * build-studio.mjs — fragment links on the Film Studio page (Elena, 24 Nov 2026)
 *
 * ADDITIVE: one marked block just before <footer> in public/aifilmstudio/index.html.
 * The page's own film loader and look are NOT edited; this block waits for the
 * films to render and adds, under each film that has a sheet, "Fragments in this
 * film #092 #071 ..." linked into the vault (/#pNNN). The other direction ("appears
 * in Arearea") is written into the vault by build-vault. Lists come from the film
 * sheets' own records (lib/films.mjs).
 *
 * History: v1 also restyled the page as a "cinema" (full-bleed frames, posters, a
 * muted hover loop). Elena, 24 Nov 2026: "it looks ugly now, bring it back exactly
 * how it looked before" — only the fragment links stay. Do not re-add the rest.
 *
 * The publisher scripts (cto-aipa atuona-add-film-to-site.py, film9-*.py) patch
 * `var SHEETS={`, the <noscript> list and the JSON-LD on this page. This block
 * contains none of those strings, and the build refuses if they change.
 *
 * Usage: node scripts/build-studio.mjs [--check]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadFilms } from './lib/films.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PAGE = join(ROOT, 'public', 'aifilmstudio', 'index.html');
const CHECK = process.argv.includes('--check');
const START = '<!-- CINEMA:START -->';
const END = '<!-- CINEMA:END -->';

const frags = {};
for (const f of loadFilms()) {
  frags[f.file] = f.poems.map(([n, t]) => [String(n).replace('#', ''), String(t)]);
}

const block = `${START}
<!-- Generated by scripts/build-studio.mjs — do not hand-edit. -->
<style id="cinema-css">
  /* Fragment links only. Sits inside the page's own .film box; no other rule of
     the page is overridden. */
  #films .film .frags{margin-top:10px;font-family:'Courier New',monospace;font-size:11px;letter-spacing:.14em;
    text-transform:uppercase;color:var(--muted);line-height:2}
  #films .film .frags a{color:var(--ink);text-decoration:none;border-bottom:1px solid #2a2a30;margin-right:10px;
    display:inline-block;white-space:nowrap;transition:color .25s,border-color .25s}
  #films .film .frags a:hover{color:var(--red);border-color:var(--red)}
</style>
<script>
(function(){
  var FRAGS=${JSON.stringify(frags)};
  function esc(s){return String(s).replace(/[&<>"]/g,function(c){return {'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c];});}
  function add(card){
    if(card.getAttribute('data-frags'))return; card.setAttribute('data-frags','1');
    var v=card.querySelector('video'); if(!v)return;
    var list=FRAGS[(v.getAttribute('src')||'').split('/').pop()];
    if(!list||!list.length)return;
    var d=document.createElement('div'); d.className='frags';
    d.innerHTML='Fragments in this film &nbsp; '+list.map(function(p){
      return '<a href="/#p'+esc(p[0])+'" title="'+esc(p[1])+'">#'+esc(p[0])+'</a>';}).join(' ');
    card.appendChild(d);
  }
  function run(){ var el=document.getElementById('films'); if(!el)return;
    Array.prototype.forEach.call(el.querySelectorAll('.film'),add); }
  var el=document.getElementById('films');
  if(el&&window.MutationObserver){ new MutationObserver(run).observe(el,{childList:true}); }
  run();
})();
</script>
${END}
`;

let html = readFileSync(PAGE, 'utf8');
const ANCHORS = ['var SHEETS={', '<noscript><div class="wrap"><h2>Films from the ATUONA AI Film Studio</h2><ul>',
  '"numberOfItems": ', "var API='https://webhook.aideazz.xyz/cto/films.json';", '<div class="wrap" id="films">'];
const snap = (s) => ANCHORS.map((a) => s.split(a).length - 1);
const before = snap(html);
const outside = (s) => {
  const a = s.indexOf(START); const b = s.indexOf(END);
  if (a < 0) return s;
  let e = b + END.length;
  if (s[e] === '\r') e += 1;
  if (s[e] === '\n') e += 1;   // the block owns the newline after its end marker
  return s.slice(0, a) + s.slice(e);
};
const outsideBefore = outside(html).replace(/\r?\n$/, '');

let action;
if (html.includes(START) && html.includes(END)) {
  const a = html.indexOf(START);
  const b = html.indexOf(END) + END.length + (html[html.indexOf(END) + END.length] === '\n' ? 1 : 0);
  html = html.slice(0, a) + block + html.slice(b);
  action = 'refreshed';
} else {
  const f = html.lastIndexOf('<footer>');
  if (f < 0) throw new Error('studio page: no <footer> — refusing to guess where the cinema layer goes');
  html = html.slice(0, f) + block + html.slice(f);
  action = 'installed';
}

const after = snap(html);
ANCHORS.forEach((a, i) => {
  if (before[i] !== after[i] || after[i] < 1) throw new Error(`studio page anchor changed: ${a} (${before[i]} → ${after[i]}) — refusing to write`);
});
// Everything outside the block must be byte-identical to what was there.
if (outside(html).replace(/\r?\n$/, '') !== outsideBefore) throw new Error('studio page changed outside the CINEMA block — refusing to write');

if (CHECK) console.log(`build-studio --check: would be ${action}. Nothing written.`);
else {
  writeFileSync(PAGE, html, 'utf8');
  console.log(`build-studio: cinema layer ${action} — ${Object.keys(frags).length} films carry fragment links; page outside the block untouched.`);
}
