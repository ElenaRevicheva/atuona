#!/usr/bin/env node
/**
 * build-studio.mjs — the Film Studio as a cinema (Elena, 24 Nov 2026)
 *
 * ADDITIVE, like build-type.mjs and build-craft.mjs: one marked block is placed
 * just before <footer> in public/aifilmstudio/index.html. The page's own film
 * loader (fetch films.json → render) is NOT edited; this block waits for it to
 * render, then dresses each film:
 *   - full-bleed frame, picture first, the sheet's still as the poster
 *   - a muted loop on hover (mouse only; never for reduced motion). The moment
 *     the viewer presses play, the loop stops and the film starts from 0:00 with
 *     sound — the preview never hijacks a real viewing.
 *   - the fragments each film quotes, linked into the vault (/#pNNN). The other
 *     direction ("appears in Arearea") is written into the vault by build-vault.
 * Fragment lists come from the film sheets' own records (lib/films.mjs).
 *
 * The publisher scripts (cto-aipa atuona-add-film-to-site.py, film9-*.py) patch
 * `var SHEETS={`, the <noscript> list and the JSON-LD on this page. This block
 * contains none of those strings, and the build refuses if they change.
 *
 * Usage: node scripts/build-studio.mjs [--check]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadFilms } from './lib/films.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PAGE = join(ROOT, 'public', 'aifilmstudio', 'index.html');
const CHECK = process.argv.includes('--check');
const START = '<!-- CINEMA:START -->';
const END = '<!-- CINEMA:END -->';

const frags = {};
for (const f of loadFilms()) {
  frags[f.file] = f.poems.map(([n, t]) => [String(n).replace('#', ''), String(t)]);
}

const block = `${START}
<!-- Generated by scripts/build-studio.mjs — do not hand-edit. -->
<style id="cinema-css">
  /* Cinema layer: added on top of the page's own rules, none of them removed. */
  .wrap#films{max-width:1180px;padding:26px 0 70px}
  #films .film{display:flex;flex-direction:column;margin:0 0 64px;border:0;border-radius:0;padding:0;background:none}
  #films .film video{order:-1;border-radius:0;width:100%;aspect-ratio:16/9;object-fit:cover;background:#000;
    margin-bottom:14px;box-shadow:0 30px 80px -40px rgba(224,20,76,.35)}
  #films .film h2,#films .film .meta,#films .film .dl,#films .film .frags{padding:0 18px}
  #films .film h2{font-size:28px}
  #films .film .frags{margin-top:12px;font-family:'Courier New',monospace;font-size:11px;letter-spacing:.14em;
    text-transform:uppercase;color:var(--muted);line-height:2}
  #films .film .frags a{color:var(--ink);text-decoration:none;border-bottom:1px solid #2a2a30;margin-right:10px;
    white-space:nowrap;transition:color .25s,border-color .25s}
  #films .film .frags a:hover{color:var(--red);border-color:var(--red)}
  #films .film.previewing video{filter:saturate(1.08) contrast(1.04)}
  @media(max-width:760px){.wrap#films{padding:14px 0 50px}#films .film h2{font-size:22px}}
</style>
<script>
(function(){
  var FRAGS=${JSON.stringify(frags)};
  var canHover=window.matchMedia&&matchMedia('(hover:hover) and (pointer:fine)').matches;
  var still=window.matchMedia&&matchMedia('(prefers-reduced-motion: reduce)').matches;
  function esc(s){return String(s).replace(/[&<>"]/g,function(c){return {'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c];});}
  function dress(card){
    if(card.getAttribute('data-cinema'))return; card.setAttribute('data-cinema','1');
    var v=card.querySelector('video'); if(!v)return;
    var name=(v.getAttribute('src')||'').split('/').pop();
    var sheets=(typeof SHEETS==='object'&&SHEETS)||{};
    if(sheets[name]&&!v.getAttribute('poster'))v.setAttribute('poster',sheets[name]+'still-1.jpg');
    var list=FRAGS[name];
    if(list&&list.length){
      var d=document.createElement('div'); d.className='frags';
      d.innerHTML='Fragments in this film &nbsp; '+list.map(function(p){
        return '<a href="/#p'+esc(p[0])+'" title="'+esc(p[1])+'">#'+esc(p[0])+'</a>';}).join('');
      card.appendChild(d);
    }
    if(!canHover||still)return;
    var preview=false, start=0;
    function stop(){ if(!preview)return; preview=false; card.classList.remove('previewing');
      v.pause(); v.loop=false; v.muted=false; try{v.currentTime=0;}catch(e){} }
    v.addEventListener('mouseenter',function(){
      if(!v.paused||v.currentTime>0)return;          /* a real viewing is never touched */
      preview=true; card.classList.add('previewing'); v.muted=true;
      start=isFinite(v.duration)&&v.duration>30?Math.floor(v.duration*0.2):0;
      try{v.currentTime=start;}catch(e){}
      var p=v.play(); if(p&&p.catch)p.catch(function(){preview=false;card.classList.remove('previewing');});
    });
    v.addEventListener('mouseleave',stop);
    v.addEventListener('timeupdate',function(){ if(preview&&v.currentTime>start+6){try{v.currentTime=start;}catch(e){}} });
    /* The viewer pressed pause/play or unmuted during the loop: that is a real
       viewing now. Start the film properly, from the beginning, with sound. */
    v.addEventListener('pause',function(){ if(!preview)return; preview=false; card.classList.remove('previewing');
      v.muted=false; try{v.currentTime=0;}catch(e){} v.play(); });
    v.addEventListener('volumechange',function(){ if(preview&&!v.muted){ preview=false; card.classList.remove('previewing'); } });
  }
  function run(){ var el=document.getElementById('films'); if(!el)return;
    Array.prototype.forEach.call(el.querySelectorAll('.film'),dress); }
  var el=document.getElementById('films');
  if(el&&window.MutationObserver){ new MutationObserver(run).observe(el,{childList:true}); }
  run();
})();
</script>
${END}
`;

let html = readFileSync(PAGE, 'utf8');
const ANCHORS = ['var SHEETS={', '<noscript><div class="wrap"><h2>Films from the ATUONA AI Film Studio</h2><ul>',
  '"numberOfItems": ', "var API='https://webhook.aideazz.xyz/cto/films.json';", '<div class="wrap" id="films">'];
const snap = (s) => ANCHORS.map((a) => s.split(a).length - 1);
const before = snap(html);
const outside = (s) => {
  const a = s.indexOf(START); const b = s.indexOf(END);
  if (a < 0) return s;
  let e = b + END.length;
  if (s[e] === '\r') e += 1;
  if (s[e] === '\n') e += 1;   // the block owns the newline after its end marker
  return s.slice(0, a) + s.slice(e);
};
const outsideBefore = outside(html).replace(/\r?\n$/, '');

let action;
if (html.includes(START) && html.includes(END)) {
  const a = html.indexOf(START);
  const b = html.indexOf(END) + END.length + (html[html.indexOf(END) + END.length] === '\n' ? 1 : 0);
  html = html.slice(0, a) + block + html.slice(b);
  action = 'refreshed';
} else {
  const f = html.lastIndexOf('<footer>');
  if (f < 0) throw new Error('studio page: no <footer> — refusing to guess where the cinema layer goes');
  html = html.slice(0, f) + block + html.slice(f);
  action = 'installed';
}

const after = snap(html);
ANCHORS.forEach((a, i) => {
  if (before[i] !== after[i] || after[i] < 1) throw new Error(`studio page anchor changed: ${a} (${before[i]} → ${after[i]}) — refusing to write`);
});
// Everything outside the block must be byte-identical to what was there.
if (outside(html).replace(/\r?\n$/, '') !== outsideBefore) throw new Error('studio page changed outside the CINEMA block — refusing to write');

if (CHECK) console.log(`build-studio --check: would be ${action}. Nothing written.`);
else {
  writeFileSync(PAGE, html, 'utf8');
  console.log(`build-studio: cinema layer ${action} — ${Object.keys(frags).length} films carry fragment links; page outside the block untouched.`);
}
