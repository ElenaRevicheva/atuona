#!/usr/bin/env node
/**
 * build-palette.mjs — the oxblood / graphite palette (Elena, 24 Nov 2026)
 *
 * Elena: "it looks like a Halloween night. Yes, it is underground aesthetic, but
 * it's aesthetic." She chose: oxblood instead of bright crimson, a graphite
 * background between black and grey, and poems in warm off-white, not pure white.
 *
 * Same contract as build-type.mjs / build-craft.mjs: ONE marked block at the end
 * of <head>, a layer and never a rewrite. Nearly every colour on the page is a
 * :root variable, so this block mostly re-points those variables; the handful of
 * hard-coded red glows get a matching quieter value. Remove the block and the
 * page is exactly as it was (restore point: git tag pre-palette-2026-11-24).
 *
 * No text, poem, link, button or script is touched — the build refuses to write
 * if any structural count changes.
 *
 * Usage:
 *   node scripts/build-palette.mjs           install / refresh the layer
 *   node scripts/build-palette.mjs --check   report, write nothing
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const HTML = join(ROOT, 'index.html');
const CHECK = process.argv.includes('--check');

const START = '<!-- PALETTE:START -->';
const END = '<!-- PALETTE:END -->';

// The palette, named once.
const P = {
  graphite: '#141414',   // page background (was #0a0a0a near-black)
  graphite2: '#1c1c1c',  // hairlines and panels (was #1a1a1a)
  paper: '#ebe8e3',      // warm off-white: poems and main text (was #e8e8e8 / #f0f0f0)
  oxblood: '#6e1a1f',    // fills, rules, borders (was #8b0000)
  oxbloodDeep: '#4a1215',
  brick: '#b0353a',      // red that must be READ as text: numbers, LIVE (was #dc143c)
  dust: '#9c4a4a',
};

const block = `${START}
    <!-- Generated by scripts/build-palette.mjs — do not hand-edit. -->
    <style id="palette-css">
        /* ── Oxblood / graphite palette ──────────────────────────────────────
           Re-points the page's own colour variables. Dark oxblood is too dark
           to read as text on graphite, so text that has to be red uses brick;
           oxblood is for fills, rules and borders. */
        :root{
            --deep-black:${P.graphite};
            --charcoal:${P.graphite2};
            --off-grey:${P.paper};
            --silver-bright:${P.paper};
            --red-crimson:${P.brick};
            --red-dark:${P.oxblood};
            --red-blood:${P.oxblood};
            --red-deep:${P.oxbloodDeep};
            --red-black:#1c1616;
            --accent-red:${P.dust};
            --gradient-primary:linear-gradient(135deg,${P.oxblood} 0%,${P.oxbloodDeep} 100%);
            --gradient-red:linear-gradient(45deg,${P.brick},${P.oxblood});
        }
        /* The poems: warm off-white, like ink on a gallery wall. */
        html body .nft-verse{color:${P.paper};}
        /* Hard-coded red glows, quieted to match. */
        html body .header{background:rgba(20,20,20,.95);box-shadow:0 4px 40px rgba(0,0,0,.45);}
        html body .site-title .russian{text-shadow:0 0 30px rgba(110,26,31,.35);animation-name:palette-breathe;}
        /* ATUONA used to cycle its hue 0 -> 90deg (red -> olive green). Elena: narrow
           it so it only breathes between brick and oxblood. Same timing, same
           alternate rhythm; only the colour range is narrowed. */
        @keyframes palette-breathe{0%{filter:brightness(1)}100%{filter:brightness(.62)}}
        html body .nft-status.live{background:rgba(110,26,31,.18);}
        /* Menu button text sat in near-black on bright red; on oxblood it needs paper. */
        html body .nav-link::after{color:${P.paper};}
        /* Text that was set in the dark red: on graphite, oxblood is too dark to
           read (it was barely readable before, too). Same places, brick instead.
           The Mint panel and Manifesto set it inline, so those need !important;
           only the colour is changed, never the words. */
        html body .hero-cta,html body .nft-action,html body .blockchain-badge,
        html body .claim-button,html body .tech-badge,html body .dna-sign{color:${P.brick};}
        html body .hero-cta:hover,html body .nft-action:hover,html body .claim-button:hover{color:${P.paper};}
        html body [style*="color: var(--red-dark)"]{color:${P.brick} !important;}
        /* The ink stain, in oxblood. */
        html body .poem-status.live::after{
            background:radial-gradient(circle,rgba(176,53,58,.6),rgba(110,26,31,.25) 45%,rgba(110,26,31,0) 70%);}
    </style>
    ${END}`;

let html = readFileSync(HTML, 'utf8');
let action;
if (html.includes(START) && html.includes(END)) {
  const a = html.indexOf(START);
  const b = html.indexOf(END) + END.length;
  html = html.slice(0, a) + block + html.slice(b);
  action = 'refreshed';
} else {
  const head = html.lastIndexOf('</head>');
  if (head < 0) throw new Error('no </head> — refusing to guess where the palette layer goes');
  html = html.slice(0, head) + block + '\n' + html.slice(head);
  action = 'installed';
}

/* The layer must not disturb anything structural. */
const counts = (s) => ({
  cards: (s.match(/<div class="nft-card">/g) || []).length,
  buttons: (s.match(/<button class="nft-action"/g) || []).length,
  slots: (s.match(/class="gallery-slot"/g) || []).length,
  poems: (s.match(/class="poem" id="p/g) || []).length,
  claims: (s.match(/claimPoem\(/g) || []).length,
});
const before = counts(readFileSync(HTML, 'utf8'));
const after = counts(html);
for (const k of Object.keys(before)) {
  if (before[k] !== after[k]) throw new Error(`${k} changed ${before[k]} → ${after[k]} — refusing to write`);
}
if ((html.match(new RegExp(START, 'g')) || []).length !== 1) throw new Error('palette layer duplicated');

if (CHECK) {
  console.log(`build-palette --check: would be ${action}. Nothing written.`);
} else {
  writeFileSync(HTML, html, 'utf8');
  console.log(`build-palette: palette ${action} — ${after.poems} poem rows, ${after.buttons} claim buttons, ${after.claims} claim calls untouched.`);
}
